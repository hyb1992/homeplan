import assert from 'node:assert/strict';
import {permitMilestones} from '../../web/purchase-tracking.mjs';
let sequence=0;const id=()=>`step-${++sequence}`;
const schedule={contract_date:'2027-01-01',interim_date:'2027-02-01',closing_date:'2027-03-01',move_in_date:'2027-03-12'};
const initial=permitMilestones(null,{permitRequired:true,contractDate:null,schedule,interim:100},id);
assert.deepEqual(initial.slice(0,4).map(row=>row.name),['약정금 지급','토지거래허가 신청','토지거래허가 승인','본계약 체결']);
assert.equal(initial.length,8);assert(initial.every(row=>row.status==='예정'&&row.completed_date===null));
initial[0].status='완료';initial[0].completed_date='2026-10-23';initial[0].memo='keep';
initial[2].status='진행 중';
const again=permitMilestones(initial,{permitRequired:true,contractDate:null,previousContractDate:null,schedule,interim:100},id);
assert.deepEqual(again,initial);assert.notEqual(again,initial);
const signed=permitMilestones(again,{permitRequired:true,contractDate:'2026-10-23',previousContractDate:null,schedule},id);
assert.equal(signed[3].completed_date,'2026-10-23');assert.equal(signed[0].memo,'keep');
const legacy=[{id:'contract',name:'매매 계약',status:'완료',planned_date:'2026-10-20',completed_date:'2026-10-20',memo:'old'}, {id:'custom',name:'직접 적은 단계',status:'진행 중',planned_date:null,completed_date:null,memo:'retain'}];
const converted=permitMilestones(legacy,{permitRequired:true,contractDate:null,previousContractDate:'2026-10-20'},id);
assert.equal(converted.length,5);assert.equal(converted[3].status,'예정');assert.equal(converted[3].completed_date,null);
assert.equal(converted[3].id,'contract');assert.equal(converted[3].memo,'old');assert.deepEqual(converted[4],legacy[1]);
assert.equal(legacy[0].status,'완료');
const ordinary=permitMilestones(null,{permitRequired:false,contractDate:'2026-10-23',schedule},id);
assert.equal(ordinary.length,4);assert.equal(ordinary[0].status,'완료');
console.log('Permit-first steps, legacy conversion, idempotence and existing records preserved.');
